/** Default retail markup multiplier for newly added models (2x wholesale still beats official labs by 60–95%). */
const RETAIL_MARKUP = 2;

const priorityFor = (s: SevenApiModelSpec): number => {
  if (s.probeStatus === 'down') return 99;
  if (s.probeStatus === 'degraded') return 5;
  return s.avgResponseSec !== null && s.avgResponseSec <= 15 ? 0 : 1;
};

/** All 41 SevenAPI upstream endpoints with exact wholesale standard + cached rates and probe-aware priority. */
export const sevenApiEndpoints: ProviderEndpoint[] = SEVENAPI_CATALOG.map((s) => ({
  modelId: s.modelId,
  provider: SEVENAPI_PROVIDER_SLUG,
  upstreamModel: s.upstreamModel,
  inputPerMillionMicros: usdToMicros(s.standardUsd),
  outputPerMillionMicros: usdToMicros(s.standardUsd),
  cachedInputPerMillionMicros: usdToMicros(s.cachedUsd),
  priority: priorityFor(s),
  enabled: s.probeStatus !== 'down',
}));

/** Retail ModelInfo entries for SevenAPI models not already defined in the base catalogue. */
export function buildSevenApiExtraModels(existingIds: ReadonlySet<string>): ModelInfo[] {
  return SEVENAPI_CATALOG.filter((s) => !existingIds.has(s.modelId)).map<ModelInfo>((s) => ({
    id: s.modelId,
    name: s.name,
    org: s.org,
    contextLength: s.contextLength,
    inputPerMillionMicros: usdToMicros(Number((s.standardUsd * RETAIL_MARKUP).toFixed(4))),
    outputPerMillionMicros: usdToMicros(Number((s.standardUsd * RETAIL_MARKUP).toFixed(4))),
    cachedInputPerMillionMicros: usdToMicros(Number((s.cachedUsd * RETAIL_MARKUP).toFixed(5))),
    tags: s.tags,
    priceChange24h: 0,
    auto: s.probeStatus === 'healthy' && Boolean(s.auto),
  }));
}
