/**
 * Upstream Provider #1: SevenAPI (`https://7api.st`, Anthropic Messages protocol).
 *
 * Security: API credentials are NEVER stored in code — set `SEVENAPI_API_KEY` (and optionally
 * `SEVENAPI_BASE_URL`) on the gateway server. Customers authenticate exclusively with Vigas keys
 * (`sk-vg-v1-...`) against `api.vigas.ai` and never see `sevenapi` or `7api.st`.
 */
export const SEVENAPI_PROVIDER_SLUG = 'sevenapi';
export const SEVENAPI_DEFAULT_BASE_URL = 'https://7api.st/v1';
export const SEVENAPI_PUBLIC_LABEL = 'vigas-edge';

export type ProbeStatus = 'healthy' | 'degraded' | 'down';

export interface SevenApiModelSpec {
  /** Canonical Vigas public model ID (e.g. `anthropic/claude-opus-5.5-max`). */
  modelId: string;
  /** Exact upstream model slug sent to `https://7api.st/v1/messages`. */
  upstreamModel: string;
  name: string;
  org: string;
  contextLength: number;
  tags: ModelTag[];
  /** Wholesale flat USD per 1M tokens (both uncached input and output). */
  standardUsd: number;
  /** Wholesale USD per 1M cached input tokens. */
  cachedUsd: number;
  /** Probe availability % (last 20 probes). */
  availabilityPct: number;
  /** Probe average response time in seconds (`null` when 0% available). */
  avgResponseSec: number | null;
  probeStatus: ProbeStatus;
  /** Eligible for `vigas/auto` when this model is newly added to the catalogue. */
  auto?: boolean;
}

